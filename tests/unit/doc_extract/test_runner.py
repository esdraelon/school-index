"""Unit tests: the extraction pipeline over a real on-disk store.

Collaborators are the real repositories and the real registry; the
only fixtures are the corpus rows and PDF bytes (generated by the
``make_pdf`` fixture). Time is injected so delta-skip proofs can
compare ``extracted_at`` stamps across runs.
"""

import hashlib
from collections.abc import Callable
from datetime import datetime, timezone
from pathlib import Path

from school_index.corpus_sync.domain import CorpusItem, ItemStatus
from school_index.corpus_sync.lookup import Found
from school_index.corpus_sync.store import CorpusStore
from school_index.doc_extract.domain import ExtractionOutcome, ExtractReport
from school_index.doc_extract.extractors import ExtractedText, build_extractors
from school_index.doc_extract.runner import ExtractionRunner
from school_index.doc_extract.store import ExtractStore

T1 = datetime(2026, 10, 23, 14, 0, tzinfo=timezone.utc)
T2 = datetime(2026, 10, 23, 15, 0, tzinfo=timezone.utc)
T3 = datetime(2026, 10, 23, 16, 0, tzinfo=timezone.utc)
T4 = datetime(2026, 10, 23, 17, 0, tzinfo=timezone.utc)


def make_item(source_ref: str, **overrides: object) -> CorpusItem:
    fields: dict[str, object] = {
        "id": hashlib.sha256(source_ref.encode("utf-8")).hexdigest(),
        "source_kind": "AGENDA",
        "source_ref": source_ref,
        "student": "sam",
        "course": "Algebra I",
        "title": "Item",
        "deep_link": source_ref.split(":", 1)[1],
        "origin_url": source_ref.split(":", 1)[1],
        "format": "pdf",
        "content_hash": "hash-1",
        "fetched_at": "2026-10-23T13:00:00+00:00",
        "status": ItemStatus.OK,
        "error": None,
    }
    fields.update(overrides)
    return CorpusItem(**fields)  # type: ignore[arg-type]


class World:
    """A temp corpus root wired with both repositories + the runner."""

    def __init__(self, root: Path) -> None:
        self.corpus = CorpusStore.open(root)
        self.extracts = ExtractStore.open(root)

    def add(self, item: CorpusItem, blob: bytes | None = None) -> CorpusItem:
        self.corpus.upsert_item(item)
        if blob is not None:
            self.corpus.write_blob(item_id=item.id, content=blob)
        return item

    def run(self, *, at: datetime) -> ExtractReport:
        runner = ExtractionRunner(
            corpus_store=self.corpus,
            extract_store=self.extracts,
            extractors=build_extractors(),
            now=lambda: at,
        )
        return runner.run()


def populated_world(
    tmp_path: Path, make_pdf: Callable[[list[str]], bytes]
) -> tuple[World, dict[str, CorpusItem]]:
    world = World(tmp_path / "corpus")
    items = {
        "good": world.add(
            make_item("sam:https://example.com/good"),
            blob=make_pdf(["First page text", "Second page text"]),
        ),
        "blank": world.add(
            make_item("sam:https://example.com/blank"), blob=make_pdf(["", ""])
        ),
        "corrupt": world.add(
            make_item("sam:https://example.com/corrupt"),
            blob=b"definitely not a pdf",
        ),
        "link": world.add(
            make_item(
                "sam:https://example.com/link",
                format="external-link",
                content_hash=None,
            )
        ),
        "docx": world.add(
            make_item("sam:https://example.com/docx", format="docx"),
            blob=b"docx bytes (no v1 extractor)",
        ),
        "failed_sync": world.add(
            make_item(
                "sam:https://example.com/failed",
                status=ItemStatus.FAILED,
                error="HTTP 403",
            )
        ),
        "gone": world.add(
            make_item(
                "sam:https://example.com/gone", status=ItemStatus.TOMBSTONED
            )
        ),
        "blobless": world.add(make_item("sam:https://example.com/blobless")),
    }
    return world, items


def test_first_run_classifies_every_item(
    tmp_path: Path, make_pdf: Callable[[list[str]], bytes]
) -> None:
    world, items = populated_world(tmp_path, make_pdf)
    report = world.run(at=T1)
    assert report.total == 8
    assert (report.extracted, report.empty, report.failed) == (1, 1, 2)
    assert report.not_extractable == 2
    assert report.not_harvested == 2
    assert report.skipped == 0
    assert len(report.failures) == 2
    tally = report.failure_tally()
    assert tally["blob missing on disk"] == 1

    good_text = world.extracts.get_text(item_id=items["good"].id)
    assert isinstance(good_text, Found)
    assert good_text.value.text == (
        "[[page 1]]\nFirst page text\n[[page 2]]\nSecond page text"
    )
    good_state = world.extracts.get_state(item_id=items["good"].id)
    assert isinstance(good_state, Found)
    assert good_state.value.page_count == 2
    assert good_state.value.char_count == len(good_text.value.text)

    blank_text = world.extracts.get_text(item_id=items["blank"].id)
    assert isinstance(blank_text, Found)
    assert blank_text.value.text == ""

    for key in ("corrupt", "blobless"):
        state = world.extracts.get_state(item_id=items[key].id)
        assert isinstance(state, Found)
        assert state.value.outcome is ExtractionOutcome.FAILED
    assert world.extracts.outcome_counts() == {
        "extracted": 1,
        "empty": 1,
        "failed": 2,
        "not-extractable": 2,
    }
    health = world.corpus.get_sync_state(source="doc-extract")
    assert isinstance(health, Found)
    assert health.value.last_status == "partial"


def test_second_run_is_delta_only_and_failures_retry(
    tmp_path: Path, make_pdf: Callable[[list[str]], bytes]
) -> None:
    world, items = populated_world(tmp_path, make_pdf)
    world.run(at=T1)
    report = world.run(at=T2)
    # extracted / empty / not-extractable all skip; both failures retry.
    assert (report.extracted, report.empty, report.not_extractable) == (0, 0, 0)
    assert report.skipped == 4
    assert report.failed == 2
    # A skipped item's records were not rewritten at T2.
    text = world.extracts.get_text(item_id=items["good"].id)
    assert isinstance(text, Found)
    assert text.value.extracted_at.startswith("2026-10-23T14:00")
    state = world.extracts.get_state(item_id=items["good"].id)
    assert isinstance(state, Found)
    assert state.value.extracted_at.startswith("2026-10-23T14:00")


class SurrogateExtractor:
    """A strategy whose pages carry a lone surrogate (live-data shape)."""

    name = "surrogate-fixture"

    def extract(self, *, path: Path) -> ExtractedText:
        return ExtractedText(pages=("glyph \udcff here",))


class ExplodingExtractor:
    """A strategy that breaks the protocol and raises."""

    name = "exploding-fixture"

    def extract(self, *, path: Path) -> ExtractedText:
        raise RuntimeError("boom")


def test_surrogate_text_is_stored_encodable(tmp_path: Path) -> None:
    world = World(tmp_path / "corpus")
    item = world.add(make_item("sam:https://example.com/glyphs"), blob=b"%PDF-x")
    runner = ExtractionRunner(
        corpus_store=world.corpus,
        extract_store=world.extracts,
        extractors={"pdf": SurrogateExtractor()},
        now=lambda: T1,
    )
    report = runner.run()
    assert report.extracted == 1
    text = world.extracts.get_text(item_id=item.id)
    assert isinstance(text, Found)
    assert text.value.text == "[[page 1]]\nglyph \ufffd here"
    text.value.text.encode("utf-8")  # the store accepted it; so must we


def test_unexpected_extractor_exception_is_contained(
    tmp_path: Path, make_pdf: Callable[[list[str]], bytes]
) -> None:
    world = World(tmp_path / "corpus")
    bad = world.add(make_item("sam:https://example.com/bad"), blob=b"%PDF-x")
    runner = ExtractionRunner(
        corpus_store=world.corpus,
        extract_store=world.extracts,
        extractors={"pdf": ExplodingExtractor()},
        now=lambda: T1,
    )
    report = runner.run()
    assert report.failed == 1
    assert report.failure_tally() == {"RuntimeError: boom": 1}
    state = world.extracts.get_state(item_id=bad.id)
    assert isinstance(state, Found)
    assert state.value.outcome is ExtractionOutcome.FAILED
    assert state.value.extractor == "exploding-fixture"


def test_hash_change_reextracts_and_healed_failure_recovers(
    tmp_path: Path, make_pdf: Callable[[list[str]], bytes]
) -> None:
    world, items = populated_world(tmp_path, make_pdf)
    world.run(at=T1)

    # A living deck changes: new bytes, new hash in the corpus row.
    changed = make_item(
        "sam:https://example.com/good", content_hash="hash-2", title="Item v2"
    )
    world.add(changed, blob=make_pdf(["Revised first page"]))
    # The corrupt item is re-harvested as a valid PDF.
    healed = make_item("sam:https://example.com/corrupt", content_hash="hash-9")
    world.add(healed, blob=make_pdf(["Now readable"]))

    report = world.run(at=T3)
    assert report.extracted == 2
    assert report.failed == 1  # only the still-missing blob
    text = world.extracts.get_text(item_id=items["good"].id)
    assert isinstance(text, Found)
    assert "Revised first page" in text.value.text
    healed_state = world.extracts.get_state(item_id=items["corrupt"].id)
    assert isinstance(healed_state, Found)
    assert healed_state.value.outcome is ExtractionOutcome.EXTRACTED
    assert healed_state.value.error is None

    # And a fully settled world: next run extracts nothing new.
    report = world.run(at=T4)
    assert report.extracted == 0
    assert report.skipped == 5
